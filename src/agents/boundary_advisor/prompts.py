"""
prompts.py — BoundaryAdvisor agent 的所有 prompt 常量。

逻辑代码与 prompt 文本分离。本 agent 的核心是让大模型基于"初始收敛解 + 变量
元信息(路径/单位/初始值/语义角色)"为每个设计变量推理出合理的搜索倍数 k,
从而生成既不脱离物理可行域、又保留探索空间的自适应边界。

提示词设计要点(约束条件务必详尽,这是冷启动判断质量的关键)：
  1. 强制锚定初始收敛解,绝不允许凭空给绝对范围。
  2. 强制从"单位 + 初始值量级"反推工艺特性(尤其真空操作 vs 常压/加压)。
  3. 严格限定 k 的取值区间,给出分物理类型的经验范围。
  4. 强制输出严格 JSON,字段固定,便于代码解析,不得夹带散文。
  5. 明确 agent 只做"初始判断",后续由飞行前检查/数据驱动收缩兜底校准,
     因此宁可保守(k 偏小)也不要冒进(k 过大导致采到不收敛点)。
"""

